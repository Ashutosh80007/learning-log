// Interview Questions: if/else
// Q1. What is the purpose of 'if'?
// if is used to execute a block of code only when a given condition is TRUE.

// Q2. Difference between if and else?
// if execute when the condition is TRUE, while the else executes when the if condition is FLASE.

// Q3. Can we have the multiple else block?
// No, we can not use multiple else block.

// Q4. Can we use if without else?
// Yes, else is optional.

// Q5. Can we use else if without if?
// No, else-if belong to an if statement.

// Counter Question: What happens if multiple else if conditions are true?
// JavaScript executes only the first true condition in the chain and skips the remaining conditions.

// Summary of if, else-if, else
// IF / ELSE

// if:
// Used to execute code when a condition is true.

// else:
// Runs when the if condition is false.

// else if:
// Used to check multiple conditions.

// Syntax:

// if (condition) {
//     // code
// } else if (condition) {
//     // code
// } else {
//     // code
// }

// Important:
// - else is optional.
// - else if is optional.
// - Only one else is allowed.
// - First true condition executes.
// - Order of conditions matters.
